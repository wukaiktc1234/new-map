-- V20261028_021__dining_table_legacy_columns.sql
--
-- 起因（P0-A）：GET /v1/pos/tables → HTTP 200 + code=500
--   栈首行：PSQLException 字段 "id" 不存在
--   SQL: SELECT id,table_number,...,created_at,updated_at FROM dining_table
--
-- 定性：库里有**两套桌台模型**——
--   ① 真实表 dining_table（table_id / table_code / seats_count / area_id / status integer …）
--   ② 实体 DiningTable（id / table_number / capacity / area(String) / status(String "available"/"occupied") …）
--   两者列名与**语义类型**都不同（status 一边 integer 一边字符串），所以查询必然 500。
--
-- 权衡（两种修法，本次选 B）：
--   A. 改实体对齐真实列 → 需要把 status 改成 integer、area 改成 Long，
--      **API JSON 会从 "available" 变成 1**，前端收银页要同步改 → 属跨端契约变更，不能在 P0 灭火里做。
--   B. 给 dining_table 补齐实体所需列（本迁移）→ 保住 API 契约、0 行表、可回滚。
--      **代价**：表里同时存在 table_code 与 table_number 等重复语义列（记 tech-debt，后续统一）。
--
-- 本迁移全部 IF NOT EXISTS，可重复执行；时间列用 timestamp without time zone（单时区假设）。
-- =====================================================================

ALTER TABLE dining_table ADD COLUMN IF NOT EXISTS id bigint GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE dining_table ADD COLUMN IF NOT EXISTS table_number varchar(64);
ALTER TABLE dining_table ADD COLUMN IF NOT EXISTS capacity integer;
ALTER TABLE dining_table ADD COLUMN IF NOT EXISTS area varchar(64);
ALTER TABLE dining_table ADD COLUMN IF NOT EXISTS qr_code varchar(255);
ALTER TABLE dining_table ADD COLUMN IF NOT EXISTS guest_count integer;
ALTER TABLE dining_table ADD COLUMN IF NOT EXISTS seated_at timestamp without time zone;
ALTER TABLE dining_table ADD COLUMN IF NOT EXISTS created_at timestamp without time zone DEFAULT CURRENT_TIMESTAMP;
ALTER TABLE dining_table ADD COLUMN IF NOT EXISTS updated_at timestamp without time zone DEFAULT CURRENT_TIMESTAMP;

COMMENT ON COLUMN dining_table.id IS '实体 DiningTable.id（@TableId）。与 table_id 并存属历史双模型，见 tech-debt-schema.md';
COMMENT ON COLUMN dining_table.table_number IS '实体 DiningTable.tableNumber（与 table_code 重复语义，tech-debt）';
COMMENT ON COLUMN dining_table.capacity IS '实体 DiningTable.capacity（与 seats_count 重复语义，tech-debt）';
COMMENT ON COLUMN dining_table.area IS '实体 DiningTable.area（字符串区域名；真实列 area_id 为 bigint，tech-debt）';
