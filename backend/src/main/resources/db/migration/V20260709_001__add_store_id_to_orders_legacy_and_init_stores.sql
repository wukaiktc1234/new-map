-- ============================================================
-- 迁移脚本：给 orders_legacy 表添加门店字段 + 清理模拟门店数据
-- 背景：POS端产生的交易行为是管理端获取订单数据的主要来源，
--       但 orders_legacy 表缺少门店字段，导致订单无法关联门店。
-- 本脚本：
--   1. 给 orders_legacy 表添加 STORE_ID 和 STORE_NAME 字段
--   2. 不再初始化模拟门店数据（改由系统初始化时真实录入）
--   3. 不强制回填现有 orders_legacy 订单的门店信息
-- ============================================================

-- ============================================================
-- 第1部分：给 orders_legacy 表添加门店字段
-- ============================================================
-- 添加门店ID字段（关联 stores 表）
ALTER TABLE orders_legacy ADD COLUMN IF NOT EXISTS STORE_ID VARCHAR(32);
-- 添加门店名称字段（冗余存储，避免频繁关联查询）
ALTER TABLE orders_legacy ADD COLUMN IF NOT EXISTS STORE_NAME VARCHAR(100);

-- 为门店ID创建索引（用于按门店聚合统计）
CREATE INDEX IF NOT EXISTS idx_orders_legacy_store_id ON orders_legacy (STORE_ID);

-- ============================================================
-- 第2部分：门店基础数据不再通过迁移脚本初始化
-- 原模拟数据（中心旗舰店/朝阳分店/海淀分店）已删除，避免硬编码
-- ============================================================

-- ============================================================
-- 第3部分：回填现有 orders_legacy 订单的门店信息
-- ============================================================
-- 不再强制回填到模拟门店；如后续有真实门店数据，可手工或通过业务脚本回填
UPDATE orders_legacy SET STORE_ID = NULL, STORE_NAME = NULL WHERE STORE_ID IS NULL;
