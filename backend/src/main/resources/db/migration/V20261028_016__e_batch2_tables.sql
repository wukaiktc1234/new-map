-- 时间列：`timestamp without time zone`，与既有表一致；系统假设单一时区 Asia/Shanghai（无夏令时）。
--   多时区部署须全库迁 timestamptz（见 docs/audit/tech-debt-schema.md P0-1）。
-- 金额列：**bigint 存分 + _fen 后缀**。注意：本批实体来源为旧模型，
--   实体里 `totalAmount/unitPrice/subtotalAmount` 等是 **BigDecimal(元)** —— 建表时**另加 *_fen 列**，
--   元列保留以兼容现有代码（不改底层逻辑，Owner 硬约束）；双写校验见 tech-debt-schema.md P1-1。
-- 每张表：主键 / deleted / create_time / update_time / 外键列建索引。
-- -- 本批：self_purchase, self_purchase_item（Owner 拍板建）, inventory_code, plan_item, receivable
-- =====================================================================

-- 1) self_purchase（自采单；写入点 SelfPurchaseServiceImpl:59/135）
CREATE TABLE IF NOT EXISTS self_purchase (
    self_purchase_id  varchar(64) NOT NULL,
    purchase_number   varchar(64),
    purchase_type     varchar(32),
    purchase_reason   varchar(500),
    total_amount      numeric(14,2),        -- 元（兼容现有代码）
    total_amount_fen  bigint,                -- 分（新标准，双写校验）
    purchase_date     timestamp without time zone,
    purchaser         varchar(100),
    purchaser_phone   varchar(32),
    purchase_location varchar(255),
    warehouse_id      bigint,
    warehouse_name    varchar(200),
    status            varchar(32) DEFAULT 'pending',
    reimburse_status  varchar(32) DEFAULT 'unreimbursed',
    remark            varchar(500),
    create_time       timestamp without time zone DEFAULT CURRENT_TIMESTAMP,
    update_time       timestamp without time zone DEFAULT CURRENT_TIMESTAMP,
    create_by         varchar(64),
    update_by         varchar(64),
    deleted           integer NOT NULL DEFAULT 0,
    CONSTRAINT self_purchase_pkey PRIMARY KEY (self_purchase_id)
);
CREATE INDEX IF NOT EXISTS idx_sp_warehouse ON self_purchase (warehouse_id);
CREATE INDEX IF NOT EXISTS idx_sp_status ON self_purchase (status) WHERE deleted = 0;

-- 2) self_purchase_item（自采明细；写入点 SelfPurchaseServiceImpl:67/129）
CREATE TABLE IF NOT EXISTS self_purchase_item (
    self_purchase_item_id varchar(64) NOT NULL,
    self_purchase_id      varchar(64) NOT NULL,
    product_id            bigint,
    product_name          varchar(200),
    specification         varchar(200),
    unit                  varchar(32),
    quantity              integer,
    unit_price            numeric(14,2),
    unit_price_fen        bigint,
    subtotal_amount       numeric(14,2),
    subtotal_amount_fen   bigint,
    status                varchar(32) DEFAULT 'pending',
    trace_code_status     varchar(32) DEFAULT 'pending',
    create_time           timestamp without time zone DEFAULT CURRENT_TIMESTAMP,
    update_time           timestamp without time zone DEFAULT CURRENT_TIMESTAMP,
    deleted               integer NOT NULL DEFAULT 0,
    CONSTRAINT self_purchase_item_pkey PRIMARY KEY (self_purchase_item_id)
);
CREATE INDEX IF NOT EXISTS idx_spi_parent ON self_purchase_item (self_purchase_id);
CREATE INDEX IF NOT EXISTS idx_spi_product ON self_purchase_item (product_id);

-- 3) inventory_code（一物一码）
CREATE TABLE IF NOT EXISTS inventory_code (
    id            bigint GENERATED BY DEFAULT AS IDENTITY,
    inventory_id  bigint,
    code_type     varchar(32),
    unique_code   varchar(128),
    batch_no      varchar(64),
    qr_code       text,
    status        integer DEFAULT 1,
    store_id      bigint,
    created_by    varchar(64),
    updated_by    varchar(64),
    create_time   timestamp without time zone DEFAULT CURRENT_TIMESTAMP,
    update_time   timestamp without time zone DEFAULT CURRENT_TIMESTAMP,
    deleted       integer NOT NULL DEFAULT 0,
    CONSTRAINT inventory_code_pkey PRIMARY KEY (id)
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_ic_code ON inventory_code (unique_code) WHERE deleted = 0;
CREATE INDEX IF NOT EXISTS idx_ic_inventory ON inventory_code (inventory_id);
CREATE INDEX IF NOT EXISTS idx_ic_store ON inventory_code (store_id);

-- 4) plan_item（采购计划明细）
CREATE TABLE IF NOT EXISTS plan_item (
    id            bigint GENERATED BY DEFAULT AS IDENTITY,
    title         varchar(200),
    description   text,
    type          varchar(32),
    priority      varchar(16),
    status        varchar(32),
    assignee      varchar(100),
    start_time    timestamp without time zone,
    end_time      timestamp without time zone,
    complete_time timestamp without time zone,
    remark        varchar(500),
    create_time   timestamp without time zone DEFAULT CURRENT_TIMESTAMP,
    update_time   timestamp without time zone DEFAULT CURRENT_TIMESTAMP,
    deleted       integer NOT NULL DEFAULT 0,
    CONSTRAINT plan_item_pkey PRIMARY KEY (id)
);
CREATE INDEX IF NOT EXISTS idx_pi_status ON plan_item (status) WHERE deleted = 0;

-- 5) receivable（应收）
CREATE TABLE IF NOT EXISTS receivable (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY,
    order_id           bigint,
    order_no           varchar(64),
    customer_id        bigint,
    customer_name      varchar(200),
    customer_type      varchar(32),
    amount             numeric(14,2),
    amount_fen         bigint,
    received_amount    numeric(14,2),
    received_amount_fen bigint,
    remaining_amount   numeric(14,2),
    remaining_amount_fen bigint,
    invoice_id         bigint,
    invoice_no         varchar(64),
    status             varchar(32),
    due_date           date,
    overdue_days       integer,
    last_received_date date,
    create_time        timestamp without time zone DEFAULT CURRENT_TIMESTAMP,
    update_time        timestamp without time zone DEFAULT CURRENT_TIMESTAMP,
    remark             varchar(500),
    deleted            integer NOT NULL DEFAULT 0,
    CONSTRAINT receivable_pkey PRIMARY KEY (id)
);
CREATE INDEX IF NOT EXISTS idx_recv_order ON receivable (order_id);
CREATE INDEX IF NOT EXISTS idx_recv_customer ON receivable (customer_id);
CREATE INDEX IF NOT EXISTS idx_recv_status ON receivable (status) WHERE deleted = 0;
