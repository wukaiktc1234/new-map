-- ⚠ 与设计稿的两处**实测偏差**（已按真实 schema 适配，见报告）：
--   1) 设计稿写 `orders.order_status = 'pending'`（字符串）；实测 orders.order_status 是 **integer**，
--      取值只有 0 / 2 / 5，**不存在 'pending'**。本迁移不改类型（历史账不回溯），
--      CAS 条件改用 **payment_status <> 2**（未支付）表达「待处理」，语义与设计稿一致。
--   2) 设计稿写 `fund_flows.amount_fen`；实测列名是 **amount**（bigint，分），按真实列名写入。

-- 1) 异常单操作流水
CREATE TABLE IF NOT EXISTS exception_ops (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id           varchar(64)  NOT NULL,
    op_type            varchar(16)  NOT NULL,               -- RESOLVE / VOID
    idempotency_key    varchar(64)  NOT NULL,
    reason             varchar(64),
    note               varchar(255),
    amount_fen         bigint,
    pay_type           varchar(16),
    cash_received_fen  bigint,
    operator_id        varchar(64)  NOT NULL,
    shift_id           bigint,
    flow_no            varchar(64),
    create_time        timestamp    NOT NULL DEFAULT now(),
    update_time        timestamp    NOT NULL DEFAULT now(),
    deleted            smallint     NOT NULL DEFAULT 0
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_exception_ops_order ON exception_ops (order_id) WHERE deleted = 0;
CREATE UNIQUE INDEX IF NOT EXISTS uk_exception_ops_idem  ON exception_ops (idempotency_key);
CREATE INDEX IF NOT EXISTS idx_exception_ops_shift       ON exception_ops (shift_id);
CREATE INDEX IF NOT EXISTS idx_exception_ops_create_time ON exception_ops (create_time);

COMMENT ON TABLE  exception_ops IS '异常单处理流水（补收款/作废），一单一条';
COMMENT ON COLUMN exception_ops.amount_fen IS '实收金额（分）；VOID 为 NULL';
COMMENT ON COLUMN exception_ops.flow_no    IS '关联资金流水号；VOID 不产生资金流水故为 NULL';

-- 2) orders 补 shift_id（交班归属）
ALTER TABLE orders ADD COLUMN IF NOT EXISTS shift_id bigint;
CREATE INDEX IF NOT EXISTS idx_orders_shift ON orders (shift_id);
COMMENT ON COLUMN orders.shift_id IS '下单所属班次；历史数据可为 NULL（不回溯）';

-- 3) 权限：先 upsert 目录，再授权给收银员
INSERT INTO permissions (permission_id_str, permission_code, permission_name, status, deleted, create_time)
SELECT 'PERM_POS_ORDER_VOID', 'pos:order:void', 'POS-作废异常单', 1, 0, now()
 WHERE NOT EXISTS (SELECT 1 FROM permissions WHERE permission_id_str = 'PERM_POS_ORDER_VOID' OR permission_code = 'pos:order:void');

-- 保证 pay 码在目录里（本迁移负责：cashier 必须同时持 pay + void）
INSERT INTO permissions (permission_id_str, permission_code, permission_name, status, deleted, create_time)
SELECT 'PERM_POS_ORDER_PAY', 'pos:order:pay', 'POS 收款', 1, 0, now()
 WHERE NOT EXISTS (SELECT 1 FROM permissions WHERE permission_code = 'pos:order:pay');

INSERT INTO role_permissions (role_id, permission_id, deleted, create_time)
SELECT 'ROLE_CASHIER', p.permission_id_str, 0, now() FROM permissions p
 WHERE p.permission_code IN ('pos:order:pay','pos:order:void')
   AND NOT EXISTS (SELECT 1 FROM role_permissions rp WHERE rp.role_id='ROLE_CASHIER' AND rp.permission_id=p.permission_id_str AND rp.deleted=0);

-- 4) 断言（只覆盖本迁移负责的对象）
DO $$
DECLARE bad int;
BEGIN
    IF to_regclass('public.exception_ops') IS NULL THEN
        RAISE EXCEPTION '迁移失败：exception_ops 表未创建';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='orders' AND column_name='shift_id') THEN
        RAISE EXCEPTION '迁移失败：orders.shift_id 未添加';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_indexes WHERE tablename='exception_ops' AND indexname='uk_exception_ops_idem') THEN
        RAISE EXCEPTION '迁移失败：idempotency_key 唯一索引缺失';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_indexes WHERE tablename='exception_ops' AND indexname='uk_exception_ops_order') THEN
        RAISE EXCEPTION '迁移失败：order_id 部分唯一索引缺失';
    END IF;
    SELECT count(*) INTO bad FROM permissions WHERE permission_code='pos:order:void' AND deleted=0;
    IF bad = 0 THEN RAISE EXCEPTION '迁移失败：权限码 pos:order:void 未登记'; END IF;
    SELECT count(DISTINCT rp.permission_id) INTO bad FROM role_permissions rp
     WHERE rp.role_id='ROLE_CASHIER' AND rp.deleted=0
       AND rp.permission_id IN ('PERM_POS_ORDER_PAY','PERM_POS_ORDER_VOID');
    IF bad <> 2 THEN RAISE EXCEPTION '迁移失败：ROLE_CASHIER 应持 pay+void 两码，实际 %', bad; END IF;
END $$;
