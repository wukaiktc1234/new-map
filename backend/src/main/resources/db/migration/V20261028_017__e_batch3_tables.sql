-- 1) requisition_requests（领用申请；主键 varchar 与实体一致）
CREATE TABLE IF NOT EXISTS requisition_requests (
    id                 varchar(64) NOT NULL,
    approval_id        varchar(64),
    employee_id        varchar(64),
    item_name          varchar(200),
    category_id        bigint,
    quantity           integer,
    unit               varchar(32),
    purpose            varchar(500),
    supplier_preference varchar(200),
    urgency_level      varchar(16),
    expected_date      date,
    department_budget  numeric(14,2),
    department_budget_fen bigint,
    estimated_cost     numeric(14,2),
    estimated_cost_fen bigint,
    created_time       timestamp without time zone DEFAULT CURRENT_TIMESTAMP,
    updated_time       timestamp without time zone DEFAULT CURRENT_TIMESTAMP,
    deleted            integer NOT NULL DEFAULT 0,
    created_by         varchar(64),
    updated_by         varchar(64),
    CONSTRAINT requisition_requests_pkey PRIMARY KEY (id)
);
CREATE INDEX IF NOT EXISTS idx_rr_approval ON requisition_requests (approval_id);
CREATE INDEX IF NOT EXISTS idx_rr_employee ON requisition_requests (employee_id);

-- 2) swap_request_details（换班申请明细）
CREATE TABLE IF NOT EXISTS swap_request_details (
    id                    varchar(64) NOT NULL,
    approval_id           varchar(64),
    initiator_id          varchar(64),
    target_employee_id    varchar(64),
    target_employee_name  varchar(100),
    original_date         date,
    original_shift_type   varchar(32),
    target_date           date,
    target_shift_type     varchar(32),
    partner_confirmed     boolean DEFAULT false,
    confirm_time          timestamp without time zone,
    coverage_plan         varchar(500),
    reason                varchar(500),
    created_time          timestamp without time zone DEFAULT CURRENT_TIMESTAMP,
    updated_time          timestamp without time zone DEFAULT CURRENT_TIMESTAMP,
    deleted               integer NOT NULL DEFAULT 0,
    created_by            varchar(64),
    updated_by            varchar(64),
    CONSTRAINT swap_request_details_pkey PRIMARY KEY (id)
);
CREATE INDEX IF NOT EXISTS idx_srd_approval ON swap_request_details (approval_id);
CREATE INDEX IF NOT EXISTS idx_srd_target ON swap_request_details (target_employee_id);

-- 3) travel_requests（出差申请）
CREATE TABLE IF NOT EXISTS travel_requests (
    id                varchar(64) NOT NULL,
    approval_id       varchar(64),
    employee_id       varchar(64),
    destination       varchar(200),
    travel_purpose    varchar(500),
    start_date        date,
    end_date          date,
    days              integer,
    estimated_budget  numeric(14,2),
    estimated_budget_fen bigint,
    actual_amount     numeric(14,2),
    actual_amount_fen bigint,
    advance_payment   numeric(14,2),
    advance_payment_fen bigint,
    daily_allowance   numeric(14,2),
    daily_allowance_fen bigint,
    transport_type    varchar(32),
    hotel_required    boolean DEFAULT false,
    hotel_city        varchar(100),
    related_task_id   varchar(64),
    created_time      timestamp without time zone DEFAULT CURRENT_TIMESTAMP,
    updated_time      timestamp without time zone DEFAULT CURRENT_TIMESTAMP,
    deleted           integer NOT NULL DEFAULT 0,
    created_by        varchar(64),
    updated_by        varchar(64),
    CONSTRAINT travel_requests_pkey PRIMARY KEY (id)
);
CREATE INDEX IF NOT EXISTS idx_tr_approval ON travel_requests (approval_id);
CREATE INDEX IF NOT EXISTS idx_tr_employee ON travel_requests (employee_id);

-- 4) weighing_record（称重记录）
CREATE TABLE IF NOT EXISTS weighing_record (
    id             bigint GENERATED BY DEFAULT AS IDENTITY,
    device_id      bigint,
    device_code    varchar(64),
    weigh_time     timestamp without time zone,
    weight_value   double precision,
    unit           varchar(16),
    business_type  varchar(32),
    business_id    bigint,
    product_id     bigint,
    product_name   varchar(200),
    operator       varchar(100),
    remark         varchar(500),
    create_time    timestamp without time zone DEFAULT CURRENT_TIMESTAMP,
    update_time    timestamp without time zone DEFAULT CURRENT_TIMESTAMP,
    create_by      varchar(64),
    update_by      varchar(64),
    deleted        integer NOT NULL DEFAULT 0,
    CONSTRAINT weighing_record_pkey PRIMARY KEY (id)
);
CREATE INDEX IF NOT EXISTS idx_wr_device ON weighing_record (device_id);
CREATE INDEX IF NOT EXISTS idx_wr_business ON weighing_record (business_type, business_id);
CREATE INDEX IF NOT EXISTS idx_wr_product ON weighing_record (product_id);
