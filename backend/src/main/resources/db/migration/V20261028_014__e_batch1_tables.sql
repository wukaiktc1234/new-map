-- 时间列：使用 `timestamp without time zone`，与既有 500+ 张表一致；
--   系统假设单一时区 Asia/Shanghai（中国无夏令时）。若将来多时区部署，
--   须全库迁移到 `timestamptz` 并同步实体类型与前端序列化（见 docs/audit/tech-debt-schema.md P0-1）。
--
-- 金额列：如本批出现金额，一律 bigint 存**分**，列名带 _fen 后缀（本批无金额列）。
--
-- ⚠ file_attachment 属**对象存储方案**（MinIO/OSS）：本表只存**元数据 + URL/存储键**，
--   **禁止存二进制**（不许 bytea/blob）；**禁止本地磁盘绝对路径**作为唯一真相（file_path 仅为兼容字段）。
--   Owner 硬约束：禁 DB Blob、禁本地磁盘。
--
-- 口径：列与实体 @TableField 一一对应（entity_column_audit 必须 0 不一致）。
