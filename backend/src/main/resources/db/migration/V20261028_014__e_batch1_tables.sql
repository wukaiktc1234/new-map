-- 1) contract_document（劳动合同文档快照）
CREATE TABLE IF NOT EXISTS contract_document (
    id               bigint GENERATED BY DEFAULT AS IDENTITY,
    contract_id      bigint,
    html_content     text,
    template_id      bigint,
    template_version varchar(64),
    document_hash    varchar(128),
    version          integer NOT NULL DEFAULT 1,
    source_type      varchar(32),
    source_desc      varchar(500),
    created_by       varchar(64),
    create_time      timestamp without time zone DEFAULT CURRENT_TIMESTAMP,
    updated_by       varchar(64),
    update_time      timestamp without time zone DEFAULT CURRENT_TIMESTAMP,
    is_current       integer NOT NULL DEFAULT 0,
    edit_remark      varchar(500),
    deleted          integer NOT NULL DEFAULT 0,
    CONSTRAINT contract_document_pkey PRIMARY KEY (id)
);
CREATE INDEX IF NOT EXISTS idx_cd_contract ON contract_document (contract_id) WHERE deleted = 0;
CREATE UNIQUE INDEX IF NOT EXISTS uk_cd_current ON contract_document (contract_id) WHERE is_current = 1 AND deleted = 0;

-- 2) file_attachment（附件元数据；**不存二进制**）
CREATE TABLE IF NOT EXISTS file_attachment (
    attachment_id   bigint GENERATED BY DEFAULT AS IDENTITY,
    tenant_id       varchar(64),
    business_type   varchar(64),
    business_id     varchar(64),
    original_name   varchar(255),
    stored_name     varchar(255),
    file_path       varchar(500),          -- 兼容字段（对象存储 key / URL），**不是本地磁盘路径**
    file_extension  varchar(32),
    content_type    varchar(128),
    file_size       bigint,                -- 字节数（不是金额）
    file_hash_md5   varchar(64),
    file_hash_sha256 varchar(128),
    storage_type    varchar(32),           -- MINIO / OSS / S3
    thumbnail_path  varchar(500),
    width           integer,
    height          integer,
    upload_user_id  varchar(64),
    upload_username varchar(100),
    download_count  bigint NOT NULL DEFAULT 0,
    status          varchar(32),
    deleted         integer NOT NULL DEFAULT 0,
    create_time     timestamp without time zone DEFAULT CURRENT_TIMESTAMP,
    update_time     timestamp without time zone DEFAULT CURRENT_TIMESTAMP,
    deleted_at      timestamp without time zone,
    CONSTRAINT file_attachment_pkey PRIMARY KEY (attachment_id)
);
CREATE INDEX IF NOT EXISTS idx_fa_business ON file_attachment (business_type, business_id) WHERE deleted = 0;
CREATE INDEX IF NOT EXISTS idx_fa_tenant ON file_attachment (tenant_id) WHERE deleted = 0;

-- 3) finance_report（财务报表主表；detail 不建，见 e-final-table-list.md）
CREATE TABLE IF NOT EXISTS finance_report (
    report_id      bigint GENERATED BY DEFAULT AS IDENTITY,
    report_name    varchar(200),
    report_type    varchar(64),
    report_period  varchar(32),           -- 如 2026-10
    status         varchar(32),
    generate_by    bigint,
    generate_time  timestamp without time zone,
    create_time    timestamp without time zone DEFAULT CURRENT_TIMESTAMP,
    update_time    timestamp without time zone DEFAULT CURRENT_TIMESTAMP,
    deleted        integer NOT NULL DEFAULT 0,
    CONSTRAINT finance_report_pkey PRIMARY KEY (report_id)
);
CREATE INDEX IF NOT EXISTS idx_fr_period ON finance_report (report_period, report_type) WHERE deleted = 0;

-- 4) hardware_config（设备配置）
CREATE TABLE IF NOT EXISTS hardware_config (
    id              bigint GENERATED BY DEFAULT AS IDENTITY,
    device_type     varchar(64),
    device_name     varchar(200),
    device_model    varchar(128),
    connection_type varchar(32),
    ip_address      varchar(64),
    port            varchar(16),
    baud_rate       varchar(16),
    port_name       varchar(64),
    api_key         varchar(255),
    config_json     text,
    status          integer DEFAULT 1,
    remark          varchar(500),
    store_id        bigint,
    created_by      varchar(64),
    updated_by      varchar(64),
    create_time     timestamp without time zone DEFAULT CURRENT_TIMESTAMP,
    update_time     timestamp without time zone DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT hardware_config_pkey PRIMARY KEY (id)
);
CREATE INDEX IF NOT EXISTS idx_hc_store ON hardware_config (store_id);   -- 外键列必须索引
CREATE INDEX IF NOT EXISTS idx_hc_type ON hardware_config (device_type);

-- 5) hardware_config_version（配置版本快照）
CREATE TABLE IF NOT EXISTS hardware_config_version (
    id              bigint GENERATED BY DEFAULT AS IDENTITY,
    hardware_id     bigint,
    device_type     varchar(64),
    device_name     varchar(200),
    device_model    varchar(128),
    connection_type varchar(32),
    ip_address      varchar(64),
    port            varchar(16),
    baud_rate       varchar(16),
    api_key         varchar(255),
    remark          varchar(500),
    status          integer DEFAULT 1,
    config_json     text,
    store_id        bigint,
    version         integer NOT NULL DEFAULT 1,
    created_by      varchar(64),
    create_time     timestamp without time zone DEFAULT CURRENT_TIMESTAMP,
    version_desc    varchar(500),
    CONSTRAINT hardware_config_version_pkey PRIMARY KEY (id)
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_hcv ON hardware_config_version (hardware_id, version);
CREATE INDEX IF NOT EXISTS idx_hcv_hardware ON hardware_config_version (hardware_id);   -- 外键列必须索引
