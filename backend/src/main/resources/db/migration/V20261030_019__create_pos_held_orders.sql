-- P0 (Owner 2026-10-30): backend-side held orders (hang-up orders) so that a held cart survives
-- device loss / browser refresh. Replaces localStorage-only holding.
--
-- Money unit: total_amount_fen is bigint FEN (never yuan). cart_data is PG native jsonb (never text).
-- Isolation: employee_id + terminal_id + store_id; terminal_id comes from the request DTO exactly
-- like pos_shifts.terminal_id (never from a HTTP header).
-- Concurrency: optimistic CAS on version (affected-rows based, no select-then-update).
--
-- Pure ASCII (Owner red line). Asserts existence only, never a global column count.

CREATE TABLE IF NOT EXISTS pos_held_orders (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_no varchar(64) NOT NULL,
  employee_id bigint NOT NULL,
  terminal_id varchar(64) NOT NULL,
  store_id bigint,
  cart_data jsonb NOT NULL,
  total_amount_fen bigint NOT NULL DEFAULT 0,
  status varchar(16) NOT NULL DEFAULT 'HOLD',
  version integer NOT NULL DEFAULT 0,
  expire_at timestamp without time zone,
  create_time timestamp without time zone NOT NULL DEFAULT now(),
  update_time timestamp without time zone NOT NULL DEFAULT now(),
  deleted smallint NOT NULL DEFAULT 0
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_pos_held_orders_no ON pos_held_orders(order_no) WHERE deleted = 0;
CREATE INDEX IF NOT EXISTS idx_pos_held_orders_scope ON pos_held_orders(employee_id, terminal_id, status, expire_at) WHERE deleted = 0;
CREATE INDEX IF NOT EXISTS idx_pos_held_orders_store ON pos_held_orders(store_id, create_time) WHERE deleted = 0;

