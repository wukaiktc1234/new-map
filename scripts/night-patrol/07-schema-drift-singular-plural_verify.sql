WITH pairs(sing, plur) AS (
  VALUES
    ('accounting_subject', 'accounting_subjects'),
    ('combo_ingredient', 'combo_ingredients'),
    ('cost_record', 'cost_records'),
    ('device_status_log', 'device_status_logs'),
    ('dining_tables', 'dining_table'),
    ('dish_combo', 'dish_combos'),
    ('dish_recipe', 'dish_recipes'),
    ('finance_invoice', 'finance_invoices'),
    ('finance_voucher', 'finance_vouchers'),
    ('finance_voucher_detail', 'finance_voucher_details'),
    ('food', 'foods'),
    ('food_category', 'food_categories'),
    ('food_trace_code', 'food_trace_codes'),
    ('inventory_warning_record', 'inventory_warning_records'),
    ('inventory_warning_rule', 'inventory_warning_rules'),
    ('member_level', 'member_levels'),
    ('recharge_plan', 'recharge_plans'),
    ('recharge_record', 'recharge_records')
)
SELECT p.sing,
       (xpath('/row/c/text()',
              query_to_xml(format('select count(*) as c from public.%I', p.sing), false, true, '')))[1]::text::bigint AS sing_rows,
       p.plur,
       (xpath('/row/c/text()',
              query_to_xml(format('select count(*) as c from public.%I', p.plur), false, true, '')))[1]::text::bigint AS plur_rows
FROM pairs p
ORDER BY p.sing;

-- ============================ D 类：疑似零行对象（reltuples 筛查，精确值见 C 类） ============================
SELECT c.relname AS table_name, c.reltuples::bigint AS est_rows, c.relkind
FROM pg_class c
JOIN pg_namespace n ON n.oid = c.relnamespace
WHERE n.nspname = 'public' AND c.relkind IN ('r', 'p') AND c.reltuples <= 0
ORDER BY c.relname;
